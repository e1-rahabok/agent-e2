"""The map of hand-offs between flows: one Mermaid chart, generated from the flows' steps, in REPOSITORY-MAP.md, section
Flows, subsection Map of hand-offs. The author reviews flows visually (author, 2026-11-25); a map drawn by hand would drift.

Run: python3 project/tools/flow_map_diagram.py           # rewrite the map in REPOSITORY-MAP.md
     python3 project/tools/flow_map_diagram.py --check   # exit 1 when the map is out of date (rules_check.py runs it)

A hand-off is '→ <flow id>' (a few words may sit between) in a step of one flow (section Checks, in order, or a Step section). A flow id without the
arrow is a reference (the same check, a see also), not a hand-off, and is not drawn.
One box per flow, grouped by kind; the box text is the file name, and a click on it opens the file on GitHub. The arrow from a health check means "a failed step
opens"; every other arrow means "hands off to".
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'harness'))
import flow_executor  # noqa: E402
import knowledge_loader  # noqa: E402

MAP = os.path.join(ROOT, 'REPOSITORY-MAP.md')
BLOB = 'https://github.com/e1-rahabok/agent-e2/blob/main/'
HEADING = '### Map of hand-offs'
INTRO = ('Generated by [`project/tools/flow_map_diagram.py`](project/tools/flow_map_diagram.py) from the steps of each flow; '
         'do not edit by hand. A box is a flow file; click it to open the file. An arrow is a step that opens or hands off to another flow '
         '([placement.md](project/knowledge-rules/placement.md), Flows).')
KINDS = (('health-check', 'Health checks'), ('troubleshooting', 'Troubleshooting'), ('decision-tree', 'Decision trees'))
# '→ id' with up to a few words between ('→ the VM: id'); a flow id without the arrow is a reference.
HAND_OFF = re.compile(r'→[^→.;\n`]{0,30}?`([a-z0-9][a-z0-9/-]+)`')


def hand_offs(docs):
    """{flow id: sorted flow ids its steps link to}."""
    flows = flow_executor.flow_ids(docs)
    out = {}
    for i in flows:
        text = '\n'.join(t for _, t in flow_executor.steps_of(docs[i]))
        out[i] = sorted({x for x in HAND_OFF.findall(text) if x in flows and x != i})
    return out


def chart(docs):
    edges = hand_offs(docs)
    node = {i: f'F{n}' for n, i in enumerate(sorted(edges))}
    lines = ['```mermaid', 'flowchart LR']
    for kind, label in KINDS:
        ids = [i for i in sorted(edges) if docs[i].meta.get('retriever_guide') == kind]
        if not ids:
            continue
        lines.append(f'  subgraph {kind.replace("-", "_")}["{label}"]')
        lines += [f'    {node[i]}["{i.rsplit("/", 1)[-1]}"]' for i in ids]
        lines.append('  end')
    for i in sorted(edges):
        lines += [f'  {node[i]} --> {node[j]}' for j in edges[i]]
    # A click opens the flow file in a new tab (a Mermaid click line); whether GitHub lets it through is tested by the author.
    for i in sorted(edges):
        title = docs[i].title.replace('"', "'")
        lines.append(f'  click {node[i]} "{BLOB}knowledge/{i}.md" "{title}" _blank')
    lines.append('```')
    return '\n'.join(lines)


def section(docs):
    return f'{HEADING}\n{INTRO}\n\n{chart(docs)}\n'


def updated(text, docs):
    """REPOSITORY-MAP.md text with the map replaced, or added at the end of section Flows."""
    new = section(docs)
    m = re.search(re.escape(HEADING) + r'\n.*?(?=\n#{2,3} |\Z)', text, re.S)
    if m:
        return text[:m.start()] + new + text[m.end():]
    m = re.search(r'\n## Flows\n.*?(?=\n## |\Z)', text, re.S)
    if not m:
        raise SystemExit('REPOSITORY-MAP.md has no section ## Flows')
    return text[:m.end()].rstrip('\n') + '\n\n' + new + text[m.end():]


def main(args):
    docs, _ = knowledge_loader.load(ROOT)
    text = open(MAP, encoding='utf-8').read()
    new = updated(text, docs)
    if '--check' in args:
        if new != text:
            print('REPOSITORY-MAP.md: the map of hand-offs is out of date; run python3 project/tools/flow_map_diagram.py')
            return 1
        return 0
    if new != text:
        open(MAP, 'w', encoding='utf-8').write(new)
        print('REPOSITORY-MAP.md: map of hand-offs updated')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
